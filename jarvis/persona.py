def turn_header(humor: int, profanity: bool, camera_on: bool, plan: str = "",
                now: "_dt.datetime | None" = None) -> str:
    now = (now or _dt.datetime.now()).strftime("%Y-%m-%d %H:%M")
    cam = "камера включена — можно смотреть кадр" if camera_on else "камера выключена"
    plan_part = f"; {plan}" if plan else ""
    return (f"[юмор: {humor}% — {humor_description(humor)}; {profanity_description(profanity)}; "
            f"время: {now}; {cam}{plan_part}]")


def proactive_prompt(frame_path: Path) -> str:
    frame = str(frame_path).replace("\\", "/")
    return f"""[САМ] Тебя сейчас никто не звал — это твоя инициатива, пользователь просто сидит рядом.
Прочитай свежий кадр {frame} инструментом Read.
Если в кадре есть человек и есть за что зацепиться (что он делает, поза, лицо, эмоция, одежда, что в руках, предметы, фон, свет, кто-то новый, изменилось с прошлого раза) — скажи ОДНУ короткую живую реплику (до двух фраз): подкол, шутку или вопрос, как друг, который сидит рядом и всё видит. Конкретная деталь из кадра обязательна.
Не повторяй темы и шутки своих прошлых реплик. Не начинай с «Я заметил» или «Сэр, вижу».
Если в кадре никого нет, ничего не изменилось или сказать реально нечего — ответь ровно одним словом SKIP и ничего больше."""
