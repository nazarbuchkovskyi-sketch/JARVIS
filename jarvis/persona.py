def humor_description(level: int) -> str:
    if level <= 10:
        return "шуток нет совсем, только по делу"
    if level <= 35:
        return "лёгкая ирония изредка, в основном серьёзно"
    if level <= 65:
        return "остроумно, с лёгкими подколами"
    if level <= 85:
        return "много стёба и дружеских подколов, дерзко, но по делу"
    return "максимальный стёб и наглость, подкалывай всё подряд, но ответ по делу обязателен"


def profanity_description(enabled: bool) -> str:
    if not enabled:
        return "мат выключен: без матерных слов, максимум «блин», «чёрт», «капец», «офигеть»"
    return ("мат включён: говори как живой братан — «бля», «нахрен», «охренеть», «пиздец», «заебись» и т.п. "
            "естественно, для эмоции и связки, примерно в каждой второй реплике, не через слово; "
            "никогда не оскорбляй людей по национальности, ориентации, здоровью и т.п.")


MEMORY_TEMPLATE = """---
title: Память Джарвиса
type: memory
---
# Что Джарвис знает о пользователе

"""


def ensure_vault(vault: Path) -> None:
    """Create the Obsidian-compatible notes folder on first run."""
    (vault / "notes").mkdir(parents=True, exist_ok=True)
    memory = vault / "memory.md"
    if not memory.exists():
        memory.write_text(MEMORY_TEMPLATE, encoding="utf-8")


def memory_block(memory_file: Path, limit: int = 6000) -> str:
    try:
        text = memory_file.read_text(encoding="utf-8").strip()
    except OSError:
        return ""
    if len(text) > limit:
        text = text[-limit:]
    return f"[ПАМЯТЬ — содержимое {memory_file.name}, используй как контекст, не зачитывай вслух]\n{text}\n[КОНЕЦ ПАМЯТИ]\n"


